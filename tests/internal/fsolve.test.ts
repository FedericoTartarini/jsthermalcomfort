// The equations scipy was run on, each written with the same operations in the
// same order as the Python one and no libm call, so both evaluate to the same
// bits.
function make(
  fam: string,
  p: readonly number[],
): (x: readonly number[]) => number[] {
  const [p0 = NaN, p1 = NaN, p2 = NaN, p3 = NaN] = p;
  switch (fam) {
    case "lin": {
      const n = p0;
      const A = p.slice(1, 1 + n * n);
      const b = p.slice(1 + n * n);
      return (x) => {
        const out: number[] = [];
        for (let i = 0; i < n; i++) {
          let s = 0.0;
          for (let j = 0; j < n; j++)
            s = s + (A[i * n + j] ?? NaN) * (x[j] ?? NaN);
          out.push(s - (b[i] ?? NaN));
        }
        return out;
      };
    }
    case "quad": {
      const c = p.slice(2);
      return (x) =>
        Array.from(
          { length: p0 },
          (_, i) =>
            (x[i] ?? NaN) * (x[i] ?? NaN) -
            (c[i] ?? NaN) +
            p1 * (x[(i + 1) % p0] ?? NaN),
        );
    }
    case "rosen":
      return (x) => [
        p0 * ((x[1] ?? NaN) - (x[0] ?? NaN) * (x[0] ?? NaN)),
        1.0 - (x[0] ?? NaN),
      ];
    case "powell":
      return (x) => [
        10000.0 * (x[0] ?? NaN) * (x[1] ?? NaN) - 1.0,
        (x[0] ?? NaN) * (x[0] ?? NaN) + (x[1] ?? NaN) * (x[1] ?? NaN) - p0,
      ];
    case "cubic":
      return (x) => [
        p0 * ((x[0] ?? NaN) - p1) * ((x[0] ?? NaN) - p2) * ((x[0] ?? NaN) - p3),
      ];
    case "noroot":
      return (x) => [(x[0] ?? NaN) * (x[0] ?? NaN) + p0];
    case "noroot2":
      return (x) => [
        (x[0] ?? NaN) * (x[0] ?? NaN) + (x[1] ?? NaN) * (x[1] ?? NaN) + p0,
        (x[0] ?? NaN) - (x[1] ?? NaN) * p1,
      ];
    case "singular":
      return (x) => [
        (x[0] ?? NaN) * (x[0] ?? NaN),
        (x[1] ?? NaN) * (x[1] ?? NaN) * (x[1] ?? NaN) - p0 * (x[0] ?? NaN),
      ];
    case "flat":
      return (x) => {
        const t = (x[0] ?? NaN) - p0;
        const t2 = t * t;
        const t4 = t2 * t2;
        return [t4 * t4 * t];
      };
    case "nan_below":
      return (x) => [
        (x[0] ?? NaN) < p0 ? NaN : (x[0] ?? NaN) * (x[0] ?? NaN) - p1,
      ];
    case "inf_at":
      return (x) => [x[0] === p0 ? Infinity : (x[0] ?? NaN) - p1];
    case "rational3":
      return (x) => [
        1.0 / (x[0] ?? NaN) - p0,
        (x[0] ?? NaN) * (x[1] ?? NaN) - p1,
        (x[1] ?? NaN) + (x[2] ?? NaN) * (x[0] ?? NaN) - p2,
      ];
    case "zero":
      return (x) => [0.0 * (x[0] ?? NaN)];
    case "step":
      return (x) => [(x[0] ?? NaN) < p0 ? -1.0 : 1.0];
  }
  throw new Error(fam);
}

